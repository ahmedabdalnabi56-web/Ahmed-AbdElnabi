const caseModal = document.getElementById('caseModal');
const caseTitle = document.getElementById('caseModalTitle');
const caseKicker = document.getElementById('caseModalKicker');
const caseSummary = document.getElementById('caseModalSummary');
const caseGrid = document.getElementById('caseModalGrid');

function openCase(key){
  const data = caseStudies[key];
  if(!data || !caseModal) return;
  caseKicker.textContent = data.kicker;
  caseTitle.textContent = data.title;
  caseSummary.textContent = data.summary;
  caseGrid.innerHTML = data.blocks.map(([label,copy]) => `<div class="modal-block"><span>${label}</span><p>${copy}</p></div>`).join('');
  caseModal.classList.add('is-open');
  caseModal.setAttribute('aria-hidden','false');
  document.body.style.overflow='hidden';
}
function closeCase(){
  if(!caseModal) return;
  caseModal.classList.remove('is-open');
  caseModal.setAttribute('aria-hidden','true');
  document.body.style.overflow='';
}
document.querySelectorAll('.case-open').forEach(card => {
  card.addEventListener('click', () => openCase(card.dataset.case));
  card.addEventListener('keydown', e => { if(e.key==='Enter' || e.key===' '){ e.preventDefault(); openCase(card.dataset.case); } });
});
document.querySelectorAll('[data-close-modal]').forEach(el => el.addEventListener('click', closeCase));
document.addEventListener('keydown', e => { if(e.key==='Escape') closeCase(); });
